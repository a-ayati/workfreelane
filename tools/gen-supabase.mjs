// Generates supabase/migrations/0002_app_tables.sql from js/services/capabilities.js,
// so the SQL permission model can never drift from the app's.  Run: node tools/gen-supabase.mjs
import { writeFileSync } from 'node:fs';
import { ROLE_CAPS, PROVIDER_ONLY, CLIENT_ONLY, IMPLICIT, WS_CAPS } from '../js/services/capabilities.js';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const out = ['-- GENERATED by tools/gen-supabase.mjs — do not edit. Permission seed + project-scoped tables with RLS.', ''];

out.push('insert into role_caps (role, cap, side_only) values');
const rc = [];
for (const [role, caps] of Object.entries(ROLE_CAPS)) for (const cap of caps) rc.push(`  (${q(role)}, ${q(cap)}, ${PROVIDER_ONLY.has(cap) ? q('provider') : CLIENT_ONLY.has(cap) ? q('client') : 'null'})`);
out.push(rc.join(',\n') + ';', '');
out.push('insert into implicit_roles (org_role, project_role) values');
out.push(Object.entries(IMPLICIT).map(([o, p]) => `  (${q(o)}, ${q(p)})`).join(',\n') + ';', '');
out.push('insert into ws_caps (role, cap) values');
out.push(Object.entries(WS_CAPS).flatMap(([r, caps]) => caps.map((c) => `  (${q(r)}, ${q(c)})`)).join(',\n') + ';', '');

// table → [view capability, write capabilities]. Rows keep the app's fields in `data` (jsonb);
// only the columns RLS needs are typed.
const PROJECT_TABLES = {
  briefs: ['brief.view', ['brief.edit', 'brief.submit']],
  deliverables: ['scope.view', ['scope.edit']],
  proposals: ['proposal.view', ['proposal.edit', 'proposal.respond']],
  proposal_items: ['proposal.view', ['proposal.edit']],
  contracts: ['contract.view', ['contract.edit', 'contract.accept']],
  change_orders: ['scope.view', ['scope.edit', 'changes.respond']],
  files: ['files.view', ['files.upload']],
  file_versions: ['files.view', ['files.upload']],
  feedback: ['feedback.view', ['feedback.write']],
  revision_rounds: ['revisions.view', ['revisions.manage', 'revisions.request']],
  approvals: ['approvals.view', ['approvals.request', 'approvals.respond']],
  invoices: ['finance.view', ['finance.manage', 'finance.pay']],
  invoice_items: ['finance.view', ['finance.manage']],
  payments: ['finance.view', ['finance.manage', 'finance.pay']],
  tasks: ['tasks.view', ['tasks.manage']],
  messages: ['messages', ['messages']],
  events: ['calendar.view', ['calendar.view']],
};
const list = (a) => `array[${a.map(q).join(', ')}]`;
for (const [t, [view, write]] of Object.entries(PROJECT_TABLES)) {
  out.push(`create table ${t} (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references projects(id) on delete cascade,
  data jsonb not null default '{}',
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index on ${t} (project_id);
create trigger t_${t} before update on ${t} for each row execute function touch_updated_at();
alter table ${t} enable row level security;
create policy ${t}_select on ${t} for select to authenticated using (project_can(project_id, ${q(view)}));
create policy ${t}_insert on ${t} for insert to authenticated with check (exists (select 1 from unnest(${list(write)}) c where project_can(project_id, c)));
create policy ${t}_update on ${t} for update to authenticated using (exists (select 1 from unnest(${list(write)}) c where project_can(project_id, c)))
  with check (exists (select 1 from unnest(${list(write)}) c where project_can(project_id, c)));
create policy ${t}_delete on ${t} for delete to authenticated using (exists (select 1 from unnest(${list(write)}) c where project_can(project_id, c)));
`);
}

out.push(`-- Activity log: append-only (no update/delete policy), finance actions hidden without finance.view.
create table activity_logs (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references projects(id) on delete cascade,
  actor_user_id uuid default auth.uid(), action text not null,
  data jsonb not null default '{}', created_at timestamptz not null default now()
);
create index on activity_logs (project_id, created_at desc);
alter table activity_logs enable row level security;
create policy activity_select on activity_logs for select to authenticated using (
  project_can(project_id, 'activity.view') and (project_can(project_id, 'finance.view') or action !~ '^(invoice|payment|deposit)\\.'));
create policy activity_insert on activity_logs for insert to authenticated with check (project_can(project_id, 'project.view'));

-- Notifications belong to one person.
create table notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  project_id uuid references projects(id) on delete cascade,
  type text not null check (type in ('message','activity','reminder','action')),
  data jsonb not null default '{}', read_at timestamptz, created_at timestamptz not null default now()
);
create index on notifications (user_id, created_at desc);
alter table notifications enable row level security;
create policy notif_select on notifications for select to authenticated using (user_id = auth.uid());
create policy notif_update on notifications for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy notif_delete on notifications for delete to authenticated using (user_id = auth.uid());
create policy notif_insert on notifications for insert to authenticated with check (project_id is null or project_can(project_id, 'project.view'));

-- Portfolio belongs to a workspace.
create table portfolio_items (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references workspaces(id) on delete cascade,
  data jsonb not null default '{}',
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
alter table portfolio_items enable row level security;
create policy portfolio_all on portfolio_items for all to authenticated using (ws_can(workspace_id, 'portfolio')) with check (ws_can(workspace_id, 'portfolio'));
`);
writeFileSync(new URL('../supabase/migrations/0002_app_tables.sql', import.meta.url), out.join('\n'));
console.log('wrote 0002_app_tables.sql');
